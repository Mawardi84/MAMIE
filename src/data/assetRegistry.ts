// Multi-Asset Registry - All supported assets for quantitative research

export type AssetCategory = 'metals' | 'forex' | 'crypto' | 'commodities' | 'indices' | 'stocks';

export interface Asset {
  symbol: string;           // Yahoo Finance symbol
  name: string;             // Display name
  shortName: string;        // Short display name
  category: AssetCategory;
  subCategory?: string;     // Further classification
  currency: string;         // Quote currency
  exchange: string;         // Exchange name
  hasCOT: boolean;          // Has CFTC COT data
  hasOptions: boolean;      // Has options chain
  tradingHours: string;     // Trading hours description
  tickSize: number;         // Minimum price movement
  description: string;      // Brief description
  color: string;            // Theme color for UI
}

